#!/usr/bin/env node
// Builds the Stronguard browser extension.
//
//   node scripts/build.js [--browser=chrome|firefox|all] [--offline] [--refresh] [--zip]
//
// Downloads (or reuses cached) filter lists, compiles them with the shared
// engine in core/, and writes ready-to-load extensions to dist/chrome and
// dist/firefox (Edge, Brave, Opera... use the chrome build).

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { CATALOG, documentLevelFor } from '../core/catalog.js';
import { parseFilterList } from '../core/parser.js';
import { DnrCompiler } from '../core/dnr.js';
import { CosmeticCompiler, SHARD_COUNT, shardFor } from '../core/cosmetic.js';
import { ENTITY_TLDS } from '../core/domains.js';
import { DEFAULT_LEVEL, MAX_LEVEL, featuresFor } from '../core/levels.js';
import { SCRIPTLETS, GENERATED_RESOURCES, helperSource } from '../extension/scriptlets/library.js';
import { loadLists } from '../network/lists.js';
import { shieldIcon, transparentPNG, TRANSPARENT_GIF, createZip } from './lib/binary.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const EXT = path.join(ROOT, 'extension');

const args = Object.fromEntries(
  process.argv.slice(2).map((a) => {
    const [k, v] = a.replace(/^--/, '').split('=');
    return [k, v === undefined ? true : v];
  }),
);
const browsers = args.browser && args.browser !== 'all' ? [args.browser] : ['chrome', 'firefox'];
const OUT = path.resolve(ROOT, args.out || 'dist');
const log = (...m) => console.log(...m);

const pkg = JSON.parse(await fs.readFile(path.join(ROOT, 'package.json'), 'utf8'));

// ---------------------------------------------------------------------------
// 1. Load and compile filter lists

const entries = CATALOG.filter((e) => e.targets.includes('extension'));
log(`Loading ${entries.length} filter lists${args.offline ? ' (offline)' : ''}...`);
const loaded = await loadLists(entries, {
  root: ROOT,
  cacheDir: path.join(ROOT, '.cache', 'lists'),
  offline: !!args.offline,
  maxAgeHours: args.refresh ? 0 : 24,
  log,
});

const dnr = new DnrCompiler();
const cosmetic = new CosmeticCompiler({ knownScriptlets: Object.keys(SCRIPTLETS) });
const parsedLists = [];
const listInfo = [];
for (const e of entries) {
  const r = loaded.get(e.id);
  const filters = [];
  let stats = null;
  if (r && r.ok) {
    stats = parseFilterList(r.text, (f) => filters.push(f));
    for (const f of filters) dnr.noteBadfilter(f);
  }
  parsedLists.push({ entry: e, filters });
  listInfo.push({
    id: e.id,
    title: e.title,
    level: e.level,
    category: e.category,
    ok: !!(r && r.ok),
    source: r ? r.source : 'missing',
    url: r && r.url,
    filters: filters.length,
    unsupported: stats ? stats.unsupported : 0,
  });
  log(`  ${r && r.ok ? '✓' : '✗'} ${e.id.padEnd(24)} L${e.level} ${String(filters.length).padStart(7)} filters  [${r ? r.source : 'missing'}]`);
}
for (const { entry, filters } of parsedLists) {
  const docLevel = documentLevelFor(entry);
  for (const f of filters) {
    if (f.type === 'network') dnr.add(f, entry.level, docLevel);
    else cosmetic.add(f, entry.level);
  }
}
const net = dnr.finalize();
cosmetic.addNetworkExceptions(net.cosmeticExceptions);
const cos = cosmetic.finalize();

const rulesetLevel = (id) => Number(/_l(\d)$/.exec(id)[1]);
let cumulative = 0;
for (let l = 1; l <= MAX_LEVEL; l++) {
  cumulative += Object.entries(net.stats.counts).filter(([id]) => rulesetLevel(id) === l).reduce((a, [, n]) => a + n, 0);
  log(`  DNR rules enabled at level ${l}: ${cumulative}`);
}

// ---------------------------------------------------------------------------
// 2. Scriptlet bundles: one file per (scriptlet, level), registered for its hosts

const helpers = helperSource();
const hostKeysSource = `
  const labels = host.split('.');
  const keys = [];
  for (let i = 0; i < labels.length; i++) keys.push(labels.slice(i).join('.'));
  for (let cut = 1; cut <= 2 && cut < labels.length; cut++) {
    const head = labels.slice(0, labels.length - cut);
    for (let i = 0; i < head.length; i++) keys.push(head.slice(i).join('.') + '.*');
  }
  keys.push('*'); // scriptlets for every site`;

function scriptletSource(name, fn, map) {
  return `/* Stronguard scriptlet "${name}" - generated by scripts/build.js */
(function () {
  'use strict';
  let host = location.hostname;
  if (!host) {
    try { host = window.top.location.hostname; } catch (e) { host = ''; }
  }
  if (!host) return;
  const map = ${JSON.stringify(map)};
${hostKeysSource}
  const calls = [];
  const seen = new Set();
  for (const k of keys) {
    const list = map[k];
    if (!list) continue;
    for (const args of list) {
      const sig = JSON.stringify(args);
      if (!seen.has(sig)) { seen.add(sig); calls.push(args); }
    }
  }
  if (!calls.length) return;
${helpers}
  const scriptlet = ${Function.prototype.toString.call(fn)};
  for (const args of calls) {
    try { scriptlet(...args); } catch (e) { /* ignore */ }
  }
})();
`;
}

const isIp = (h) => /^\d+\.\d+\.\d+\.\d+$/.test(h);
function matchPatterns(hosts) {
  const out = new Set();
  for (const h of hosts) {
    if (h === '*') {
      out.add('<all_urls>');
      continue;
    }
    const expanded = h.endsWith('.*') ? ENTITY_TLDS.map((t) => `${h.slice(0, -2)}.${t}`) : [h];
    for (const e of expanded) {
      if (!/^[a-z0-9.-]+$/.test(e) || e.startsWith('.') || e.endsWith('.')) continue;
      out.add(isIp(e) ? `*://${e}/*` : `*://*.${e}/*`);
    }
  }
  return out.has('<all_urls>') ? ['<all_urls>'] : [...out].sort();
}

const scriptletFiles = []; // { path, source }
const scriptletIndex = [];
for (const [name, hosts] of Object.entries(cos.scriptlets)) {
  const fn = SCRIPTLETS[name];
  if (!fn) continue;
  for (let level = 1; level <= MAX_LEVEL; level++) {
    const map = {};
    for (const [host, list] of Object.entries(hosts)) {
      const args = list.filter(([, l]) => l === level).map(([a]) => a);
      if (args.length) map[host] = args;
    }
    const hostList = Object.keys(map);
    if (!hostList.length) continue;
    const file = `content/scriptlets/${name}.L${level}.js`;
    scriptletFiles.push({ path: file, source: scriptletSource(name, fn, map) });
    scriptletIndex.push({ id: `${name}-L${level}`, name, level, file, hosts: hostList.length, matches: matchPatterns(hostList) });
  }
}
log(`  Scriptlet bundles: ${scriptletIndex.length} (${scriptletIndex.reduce((a, s) => a + s.matches.length, 0)} match patterns)`);

// ---------------------------------------------------------------------------
// 3. Cosmetic shards

const shards = Array.from({ length: SHARD_COUNT }, () => ({}));
for (const [host, entry] of Object.entries(cos.specific)) shards[shardFor(host)][host] = entry;

// ---------------------------------------------------------------------------
// 4. Write each browser build

async function copyDir(src, dst, filter = () => true) {
  await fs.mkdir(dst, { recursive: true });
  for (const ent of await fs.readdir(src, { withFileTypes: true })) {
    const s = path.join(src, ent.name);
    const d = path.join(dst, ent.name);
    if (!filter(s, ent)) continue;
    if (ent.isDirectory()) await copyDir(s, d, filter);
    else await fs.copyFile(s, d);
  }
}

async function write(file, data) {
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, data);
}

const rulesetIds = Object.keys(net.rulesets).sort((a, b) => rulesetLevel(a) - rulesetLevel(b) || a.localeCompare(b));

function manifestFor(browser) {
  const m = {
    manifest_version: 3,
    name: 'Stronguard',
    short_name: 'Stronguard',
    version: pkg.version,
    description: 'Multi-layer, aggressive ad, popup and tracker blocker with a 1-5 protection level slider.',
    icons: { 16: 'icons/on-16.png', 32: 'icons/on-32.png', 48: 'icons/on-48.png', 128: 'icons/on-128.png' },
    action: {
      default_popup: 'ui/popup.html',
      default_title: 'Stronguard',
      default_icon: { 16: 'icons/on-16.png', 32: 'icons/on-32.png' },
    },
    options_ui: { page: 'ui/options.html', open_in_tab: true },
    permissions: [
      'declarativeNetRequest',
      'declarativeNetRequestFeedback',
      'scripting',
      'storage',
      'unlimitedStorage',
      'webNavigation',
      'tabs',
      'alarms',
      'contextMenus',
    ],
    host_permissions: ['<all_urls>'],
    declarative_net_request: {
      rule_resources: rulesetIds.map((id) => ({ id, enabled: rulesetLevel(id) <= DEFAULT_LEVEL, path: `rules/${id}.json` })),
    },
    web_accessible_resources: [{ resources: ['resources/*', 'ui/blocked.html'], matches: ['<all_urls>'] }],
    commands: {
      'pick-element': { suggested_key: { default: 'Alt+Shift+X' }, description: 'Pick an element to hide' },
    },
  };
  if (browser === 'firefox') {
    m.background = { scripts: ['background/main.js'], type: 'module' };
    m.browser_specific_settings = {
      gecko: { id: 'stronguard@stronguard.app', strict_min_version: '128.0', data_collection_permissions: { required: ['none'] } },
    };
  } else {
    m.background = { service_worker: 'background/main.js', type: 'module' };
    m.minimum_chrome_version = '121';
  }
  return m;
}

async function listFiles(dir, base = dir) {
  const out = [];
  for (const ent of await fs.readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) out.push(...(await listFiles(p, base)));
    else out.push(path.relative(base, p));
  }
  return out.sort();
}

const builtAt = new Date().toISOString();
const isoDate = builtAt.slice(0, 10);

for (const browser of browsers) {
  const dir = path.join(OUT, browser);
  await fs.rm(dir, { recursive: true, force: true });
  log(`Writing ${path.relative(ROOT, dir)}...`);

  await copyDir(path.join(EXT, 'background'), path.join(dir, 'background'));
  await copyDir(path.join(EXT, 'ui'), path.join(dir, 'ui'));
  await copyDir(path.join(EXT, 'resources'), path.join(dir, 'resources'));
  await copyDir(path.join(ROOT, 'core'), path.join(dir, 'core'), (p) => p.endsWith('.js') || !path.extname(p));
  await write(path.join(dir, 'content/picker.js'), await fs.readFile(path.join(EXT, 'content/picker.js')));

  // Level-specific content scripts
  const isolated = await fs.readFile(path.join(EXT, 'content/isolated.js'), 'utf8');
  const guard = await fs.readFile(path.join(EXT, 'content/guard.js'), 'utf8');
  for (let l = 1; l <= MAX_LEVEL; l++) {
    const features = JSON.stringify(featuresFor(l));
    await write(path.join(dir, `content/isolated.L${l}.js`), isolated.replaceAll('__SG_FEATURES__', features));
    await write(path.join(dir, `content/guard.L${l}.js`), guard.replaceAll('__SG_FEATURES__', features));
  }
  for (const f of scriptletFiles) await write(path.join(dir, f.path), f.source);

  // Rules and data
  for (const id of rulesetIds) await write(path.join(dir, `rules/${id}.json`), JSON.stringify(net.rulesets[id]));
  await write(path.join(dir, 'data/generic.json'), JSON.stringify(cos.generic));
  for (let i = 0; i < SHARD_COUNT; i++) await write(path.join(dir, `data/specific/${i}.json`), JSON.stringify(shards[i]));
  await write(path.join(dir, 'data/scriptlets.json'), JSON.stringify(scriptletIndex.map(({ hosts, ...s }) => s)));
  await write(
    path.join(dir, 'data/build-info.json'),
    JSON.stringify(
      {
        version: pkg.version,
        browser,
        builtAt,
        rulesets: Object.fromEntries(rulesetIds.map((id) => [id, { level: rulesetLevel(id), count: net.rulesets[id].length }])),
        lists: listInfo,
        scriptletBundles: scriptletIndex.map(({ id, name, level, hosts }) => ({ id, name, level, hosts })),
        stats: { network: net.stats, cosmetic: cos.stats },
      },
      null,
      1,
    ),
  );

  // Images
  for (const s of [16, 32, 48, 128]) {
    await write(path.join(dir, `icons/on-${s}.png`), shieldIcon(s, true));
    await write(path.join(dir, `icons/off-${s}.png`), shieldIcon(s, false));
  }
  for (const [name, fn] of Object.entries(GENERATED_RESOURCES)) {
    await write(path.join(dir, `resources/${name}`), `/* Stronguard neutered resource (generated) */\n(${Function.prototype.toString.call(fn)})();\n`);
  }
  await write(path.join(dir, 'resources/1x1.gif'), TRANSPARENT_GIF);
  await write(path.join(dir, 'resources/2x2.png'), transparentPNG(2, 2));
  await write(path.join(dir, 'resources/3x2.png'), transparentPNG(3, 2));
  await write(path.join(dir, 'resources/32x32.png'), transparentPNG(32, 32));

  await write(path.join(dir, 'manifest.json'), JSON.stringify(manifestFor(browser), null, 2));

  if (args.zip) {
    const files = await listFiles(dir);
    const zip = createZip(await Promise.all(files.map(async (name) => ({ name, data: await fs.readFile(path.join(dir, name)) }))));
    const zipName = path.join(OUT, `stronguard-${browser}-${pkg.version}-${isoDate}.zip`);
    await fs.writeFile(zipName, zip);
    log(`  Packed ${path.relative(ROOT, zipName)} (${(zip.length / 1048576).toFixed(1)} MB)`);
  }
}

const missing = listInfo.filter((l) => !l.ok);
if (missing.length) log(`\nWarning: ${missing.length} list(s) unavailable: ${missing.map((l) => l.id).join(', ')}`);
log(`\nDone. Load dist/chrome (Chrome, Edge, Brave) or dist/firefox as an unpacked extension.`);
